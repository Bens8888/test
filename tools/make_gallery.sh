#!/usr/bin/env bash
# Preview gallery: generated layouts rendered to PNG (core renderer) with their reports.
# Usage: tools/make_gallery.sh [build dir]   (writes docs/gallery/*.png and docs/GALLERY.md)
set -euo pipefail
B=${1:-build}
OUT=docs/gallery
mkdir -p "$OUT"
MD=docs/GALLERY.md
{
  echo "# Preview gallery"
  echo
  echo "Generated by \`tools/make_gallery.sh\` with the core renderer, drawn like the editor: blocks"
  echo "(default look; outline silhouettes with --look 0), spikes, saws, orbs and pads in their colours, portals as bars (gamemode green,"
  echo "speed orange, gravity/size blue), the floor and ceiling of flying stretches. The bot's path is"
  echo "white (green while the button is held). Each image is the whole level, wrapped into rows."
  echo
} > "$MD"
run() { # name, source, extra args, description
  local name=$1 src=$2 args=$3 desc=$4
  echo "== $name"
  local rep
  rep=$("$B/tools/alcli" generate "$src" $args --png "$OUT/$name.png" 2>/dev/null | grep -E "^(BEATABLE|NOT|longest|recording)" || true)
  {
    echo "## $desc"
    echo
    echo "\`alcli generate $src $args\`"
    echo
    echo '```'
    echo "$rep"
    echo '```'
    echo
    echo "![$name](gallery/$name.png)"
    echo
  } >> "$MD"
}
run style_rail demo "--seed 9 --difficulty 4 --structure 1 --crop 0:4000" "Demo song, Insane, Rail structures"
run style_slope demo "--seed 9 --difficulty 4 --structure 2 --crop 0:4000" "Demo song, Insane, Slope structures"
run style_compact demo "--seed 9 --difficulty 4 --structure 3 --crop 0:4000" "Demo song, Insane, Compact structures"
run style_spiky demo "--seed 9 --difficulty 4 --structure 4 --crop 0:4000" "Demo song, Insane, Spiky structures"
# close-ups at editor scale (one screen of the level, with the bot's path)
echo "wrote $MD"
